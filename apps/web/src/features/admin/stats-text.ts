export const statsTitle = (id: string) =>
  (TITLES as Record<string, () => string>)[id]?.() ?? id;

export const statsColumnLabel = (id: string) =>
  (COLUMNS as Record<string, () => string>)[id]?.() ?? id;

export function statsLabelText(cell: Cell): string {
  const { id, param } = parseStatsRef(String(cell));
  return (
    (CELLS as Record<string, (param: string) => string>)[id]?.(param ?? "") ??
    String(cell)
  );
}

const ORIGIN_WORDS: Record<
  EventStatistics["filterSummary"]["origins"][number],
  () => string
> = {
  blocker: () => t`blockers`,
  proposal: () => t`proposal sessions`,
  organizer: () => t`organizer sessions`,
  spontaneous: () => t`spontaneous sessions`,
};

export function filterSummaryText(
  summary: EventStatistics["filterSummary"],
  locale: string
) {
  const parts = [
    summary.locations > 0 &&
      plural(summary.locations, { one: "# location", other: "# locations" }),
    summary.hosts > 0 &&
      plural(summary.hosts, { one: "# host", other: "# hosts" }),
    ...summary.origins.map((origin) => ORIGIN_WORDS[origin]()),
  ].filter((part): part is string => Boolean(part));
  if (parts.length === 0) return t`No exclusions`;
  const list = formatList(locale, parts);
  return t`Excluding ${list}`;
}
