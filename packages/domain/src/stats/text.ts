export type StatsTitleId = keyof typeof STATS_TITLES;
export type StatsColumnId = keyof typeof STATS_COLUMNS;
export type StatsCellId = keyof typeof STATS_CELLS;

export const statsRef = (id: StatsCellId, param?: string) =>
  param === undefined ? id : `${id}:${param}`;

export function parseStatsRef(cell: string): {
  id: string;
  param: string | undefined;
} {
  const at = cell.indexOf(":");
  return at < 0
    ? { id: cell, param: undefined }
    : { id: cell.slice(0, at), param: cell.slice(at + 1) };
}

export function statsCellEnglish(cell: string): string {
  const { id, param } = parseStatsRef(cell);
  if (id === "contactType")
    return CONTACT_TYPE_LABELS[param as ContactType] ?? param ?? id;
  const text = (STATS_CELLS as Record<string, string>)[id];
  return text === undefined ? cell : text.replace("{param}", param ?? "");
}
