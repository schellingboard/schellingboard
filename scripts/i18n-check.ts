// Checks the message catalogs (docs/dev/i18n.md): a fresh `lingui extract`
// changes nothing, and every translated locale has all the source messages.
//
//     bun scripts/i18n-check.ts

import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { missingKeys, parsePo } from "./i18n-catalogs";

const webDir = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "apps/web"
);
const localesDir = path.join(webDir, "locales");
const SOURCE = "en";
// Generated by Lingui from the source catalog, never translated.
const PSEUDO = "pseudo-LOCALE";

const catalogPath = (locale: string) =>
  path.join(localesDir, locale, "messages.po");
const locales = readdirSync(localesDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name);
const read = () =>
  Object.fromEntries(
    locales.map((l) => [l, readFileSync(catalogPath(l), "utf8")])
  );

const before = read();
execFileSync("bun", ["x", "lingui", "extract", "--clean"], {
  cwd: webDir,
  stdio: "ignore",
});
const after = read();

const problems: string[] = [];
for (const locale of locales) {
  if (before[locale] !== after[locale])
    problems.push(
      `${locale}: catalog was out of date; "lingui extract" updated it, commit the result (make i18n-extract)`
    );
}

const source = parsePo(after[SOURCE]);
for (const locale of locales) {
  if (locale === SOURCE || locale === PSEUDO) continue;
  const missing = missingKeys(source, parsePo(after[locale]));
  if (missing.length)
    problems.push(
      `${locale}: ${missing.length} untranslated, e.g. ${JSON.stringify(missing[0])}`
    );
}

if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}
console.log(`Catalogs ok (${locales.join(", ")})`);
